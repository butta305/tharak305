let day= 3;

switch(day)
{
    case 1:                   // use char as well ex: let day = 'a'
    console.log("monday");    //  case 'a'
    break;

    case 2:
    console.log("tuesday");
    break;

    case 3:
    console.log("wednesday");
    

    case 4:
    console.log("thursday");
    

    case 5:
    console.log("friday");
    
    
    case 6:
    console.log("saturday");
   

    case 7:
    console.log("sunday");
    

default:
console.log("invalid entry");
    
}